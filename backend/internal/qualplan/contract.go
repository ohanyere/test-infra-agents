// Package qualplan owns the automatic qualification suite builder.
//
// Chain: AgentVersion -> claimed capabilities -> coverage contract ->
// required Task Families/case types -> eligible Evaluation Tasks ->
// certification eligibility -> environment executability -> deterministic
// task selection -> immutable Qualification Suite (existing EvaluationSuite /
// SuiteVersion) -> existing SuiteExecution -> existing QualificationPolicy.
//
// A plan is READY / PARTIAL / BLOCKED. READY means Evalplane can construct
// an authoritative qualification suite; it never means the agent is
// qualified. No LLM is used anywhere in this package: selection is a pure
// deterministic function of the inputs.
package qualplan

import (
	"github.com/evalplane/evalplane/backend/internal/competency"
	"github.com/evalplane/evalplane/backend/internal/coverage"
	"github.com/evalplane/evalplane/backend/internal/environment"
	"github.com/evalplane/evalplane/backend/internal/runtimecontract"
	"github.com/evalplane/evalplane/backend/internal/scenariocertification"
)

const (
	// PlannerContractVersion pins the planning logic. Every generated plan
	// and suite pins it so historical suites stay interpretable.
	PlannerContractVersion = "qualification-suite-planner:v1"

	// SuitePurpose marks suites generated by this planner.
	SuitePurpose = "qualification"

	// CoverageContractV2 is the coverage contract this planner builds
	// against (V1 requirements preserved, GitOps/delivery added).
	CoverageContractVersion = coverage.CoverageContractV2
	// CoverageContractV1 is preserved for per-capability pins and
	// reproducibility of historical assessments.
	CoverageContractV1 = coverage.CoverageContractVersion

	// TaskFamilyContractVersion pins the task-family catalog.
	TaskFamilyContractVersion = coverage.TaskFamilyContractVersion

	// CapabilityCatalogVersion pins the competency catalog.
	CapabilityCatalogVersion = competency.ContractVersion

	// CertificationContractVersion pins authoritative eligibility.
	CertificationContractVersion = scenariocertification.CertificationContractVersion
	// EvaluatorVersion pins the deterministic grader.
	EvaluatorVersion = scenariocertification.EvaluatorVersion
	// EnvironmentProfileContractVersion pins profile composition.
	EnvironmentProfileContractVersion = environment.ProfileCatalogVersion
	// EnvironmentRequirementsContractVersion pins requirement semantics.
	EnvironmentRequirementsContractVersion = environment.RequirementsContractVersion
	// SchedulerContractVersion pins scheduler semantics.
	SchedulerContractVersion = environment.SchedulerContractVersion
	// RuntimeContractVersion pins the supported runtime.
	RuntimeContractVersion = environment.DefaultRuntimeContract
	// InfrastructureCapabilityCatalogVersion aliases the competency catalog
	// for reproducibility manifests.
	InfrastructureCapabilityCatalogVersion = runtimecontract.InfrastructureCapabilityCatalogVersion
)

// Plan states. Machine-readable only; the frontend renders labels.
const (
	StateReady   = "ready"
	StatePartial = "partial"
	StateBlocked = "blocked"
)

// Blocker codes. Stable, machine-readable; never UI prose.
const (
	BlockerNoCapabilityClaims             = "no_capability_claims"
	BlockerCoverageRequirementUnavailable = "coverage_requirement_unavailable"
	BlockerRequiredTaskFamilyUnavailable  = "required_task_family_unavailable"
	BlockerRequiredCaseTypeUnavailable    = "required_case_type_unavailable"
	BlockerTaskNotCertified               = "task_not_certified"
	BlockerTaskCertificationStale         = "task_certification_stale"
	BlockerEnvironmentUnavailable         = "environment_unavailable"
	BlockerRuntimeContractUnsupported     = "runtime_contract_unsupported"
	BlockerAgentRuntimeIncompatible       = "agent_runtime_capability_incompatible"
	BlockerInsufficientIndependentFamiles = "insufficient_independent_families"
	BlockerInsufficientValidCandidates    = "insufficient_valid_task_candidates"
	BlockerQualificationPolicyUnavailable = "qualification_policy_unavailable"
)

// IsPlanState reports whether value is a stored plan state.
func IsPlanState(value string) bool {
	switch value {
	case StateReady, StatePartial, StateBlocked:
		return true
	default:
		return false
	}
}

// IsBlockerCode reports whether value is a known planner blocker code.
func IsBlockerCode(value string) bool {
	switch value {
	case BlockerNoCapabilityClaims,
		BlockerCoverageRequirementUnavailable,
		BlockerRequiredTaskFamilyUnavailable,
		BlockerRequiredCaseTypeUnavailable,
		BlockerTaskNotCertified,
		BlockerTaskCertificationStale,
		BlockerEnvironmentUnavailable,
		BlockerRuntimeContractUnsupported,
		BlockerAgentRuntimeIncompatible,
		BlockerInsufficientIndependentFamiles,
		BlockerInsufficientValidCandidates,
		BlockerQualificationPolicyUnavailable:
		return true
	default:
		return false
	}
}
